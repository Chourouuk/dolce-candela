-- =====================================================================
--  Dolce Candela - Schéma initial
--  Compatible PostgreSQL 14+ (et H2 en mode PostgreSQL pour les tests)
--  Montants en dinars tunisiens : NUMERIC(10,3) (3 décimales = millimes)
-- =====================================================================

-- ---------------------------------------------------------------------
-- Utilisateurs (clients + administrateurs)
-- ---------------------------------------------------------------------
CREATE TABLE users (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name           VARCHAR(120)  NOT NULL,
    email               VARCHAR(160)  NOT NULL,
    phone               VARCHAR(30),
    password_hash       VARCHAR(100)  NOT NULL,
    role                VARCHAR(20)   NOT NULL DEFAULT 'CUSTOMER',
    preferred_language  VARCHAR(2)    NOT NULL DEFAULT 'fr',
    enabled             BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT ck_users_role CHECK (role IN ('CUSTOMER', 'ADMIN')),
    CONSTRAINT ck_users_lang CHECK (preferred_language IN ('fr', 'ar', 'en'))
);

-- ---------------------------------------------------------------------
-- Catalogue
-- ---------------------------------------------------------------------
CREATE TABLE categories (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug            VARCHAR(80)   NOT NULL,
    name_fr         VARCHAR(120)  NOT NULL,
    name_ar         VARCHAR(120)  NOT NULL,
    name_en         VARCHAR(120),
    description_fr  VARCHAR(1000),
    description_ar  VARCHAR(1000),
    description_en  VARCHAR(1000),
    display_order   INT           NOT NULL DEFAULT 0,
    active          BOOLEAN       NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_categories_slug UNIQUE (slug)
);

CREATE TABLE products (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id     BIGINT        NOT NULL,
    slug            VARCHAR(120)  NOT NULL,
    name_fr         VARCHAR(150)  NOT NULL,
    name_ar         VARCHAR(150)  NOT NULL,
    name_en         VARCHAR(150),
    description_fr  VARCHAR(2000),
    description_ar  VARCHAR(2000),
    description_en  VARCHAR(2000),
    price           NUMERIC(10,3) NOT NULL,
    stock_quantity  INT           NOT NULL DEFAULT 0,
    made_to_order   BOOLEAN       NOT NULL DEFAULT FALSE,  -- fabriqué sur commande : pas de contrôle de stock
    customizable    BOOLEAN       NOT NULL DEFAULT FALSE,
    badge           VARCHAR(20),
    active          BOOLEAN       NOT NULL DEFAULT TRUE,
    version         BIGINT        NOT NULL DEFAULT 0,      -- verrouillage optimiste (stock)
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_products_slug UNIQUE (slug),
    CONSTRAINT fk_products_category FOREIGN KEY (category_id) REFERENCES categories (id),
    CONSTRAINT ck_products_price CHECK (price >= 0),
    CONSTRAINT ck_products_stock CHECK (stock_quantity >= 0),
    CONSTRAINT ck_products_badge CHECK (badge IS NULL OR badge IN ('BESTSELLER', 'NEW', 'LIMITED'))
);
CREATE INDEX idx_products_category ON products (category_id);
CREATE INDEX idx_products_active ON products (active);

CREATE TABLE product_images (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id  BIGINT        NOT NULL,
    url         VARCHAR(500)  NOT NULL,
    alt_text    VARCHAR(200),
    position    INT           NOT NULL DEFAULT 0,
    is_main     BOOLEAN       NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_product_images_product FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE CASCADE
);
CREATE INDEX idx_product_images_product ON product_images (product_id);

-- Options de personnalisation : couleurs, parfums, tailles, emballages
CREATE TABLE customization_options (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    option_type  VARCHAR(20)   NOT NULL,
    code         VARCHAR(50)   NOT NULL,
    label_fr     VARCHAR(100)  NOT NULL,
    label_ar     VARCHAR(100)  NOT NULL,
    label_en     VARCHAR(100),
    hex_color    VARCHAR(7),
    extra_price  NUMERIC(10,3) NOT NULL DEFAULT 0,
    active       BOOLEAN       NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_customization_type_code UNIQUE (option_type, code),
    CONSTRAINT ck_customization_type CHECK (option_type IN ('COLOR', 'SCENT', 'SIZE', 'PACKAGING')),
    CONSTRAINT ck_customization_extra CHECK (extra_price >= 0)
);

-- Options autorisées pour chaque produit
CREATE TABLE product_customization_options (
    product_id  BIGINT NOT NULL,
    option_id   BIGINT NOT NULL,
    PRIMARY KEY (product_id, option_id),
    CONSTRAINT fk_pco_product FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE CASCADE,
    CONSTRAINT fk_pco_option  FOREIGN KEY (option_id) REFERENCES customization_options (id) ON DELETE CASCADE
);

-- ---------------------------------------------------------------------
-- Commandes
-- ---------------------------------------------------------------------
CREATE TABLE orders (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference            VARCHAR(30)   NOT NULL,
    user_id              BIGINT,                      -- NULL = commande invité
    order_type           VARCHAR(20)   NOT NULL DEFAULT 'STANDARD',
    status               VARCHAR(20)   NOT NULL DEFAULT 'PENDING',
    customer_name        VARCHAR(120)  NOT NULL,
    customer_phone       VARCHAR(30)   NOT NULL,
    customer_email       VARCHAR(160),
    occasion             VARCHAR(30),
    budget               NUMERIC(10,3),
    reference_image_url  VARCHAR(500),
    notes                VARCHAR(2000),
    quoted               BOOLEAN       NOT NULL DEFAULT TRUE,  -- FALSE tant qu'une commande perso n'a pas de prix
    subtotal             NUMERIC(10,3) NOT NULL DEFAULT 0,
    delivery_fee         NUMERIC(10,3) NOT NULL DEFAULT 0,
    total                NUMERIC(10,3) NOT NULL DEFAULT 0,
    deposit_amount       NUMERIC(10,3) NOT NULL DEFAULT 0,
    created_at           TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at           TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_orders_reference UNIQUE (reference),
    CONSTRAINT fk_orders_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT ck_orders_type CHECK (order_type IN ('STANDARD', 'CUSTOM')),
    CONSTRAINT ck_orders_status CHECK (status IN ('PENDING', 'CONFIRMED', 'IN_PREPARATION', 'READY_FOR_PICKUP',
                                                  'SHIPPED', 'DELIVERED', 'CANCELLED')),
    CONSTRAINT ck_orders_occasion CHECK (occasion IS NULL OR occasion IN ('BIRTHDAY', 'WEDDING', 'ENGAGEMENT', 'BIRTH',
                                                  'HOLIDAY', 'CORPORATE', 'OTHER')),
    CONSTRAINT ck_orders_amounts CHECK (subtotal >= 0 AND delivery_fee >= 0 AND total >= 0 AND deposit_amount >= 0)
);
CREATE INDEX idx_orders_user ON orders (user_id);
CREATE INDEX idx_orders_status ON orders (status);
CREATE INDEX idx_orders_created ON orders (created_at);

CREATE TABLE order_items (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id      BIGINT        NOT NULL,
    product_id    BIGINT,                         -- NULL pour une création 100 % personnalisée
    product_name  VARCHAR(150)  NOT NULL,         -- copie figée du nom au moment de la commande
    unit_price    NUMERIC(10,3) NOT NULL,
    quantity      INT           NOT NULL,
    line_total    NUMERIC(10,3) NOT NULL,
    custom_text   VARCHAR(200),
    CONSTRAINT fk_order_items_order FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE CASCADE,
    CONSTRAINT fk_order_items_product FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE SET NULL,
    CONSTRAINT ck_order_items_qty CHECK (quantity > 0 AND quantity <= 100),
    CONSTRAINT ck_order_items_amounts CHECK (unit_price >= 0 AND line_total >= 0)
);
CREATE INDEX idx_order_items_order ON order_items (order_id);
CREATE INDEX idx_order_items_product ON order_items (product_id);

-- Personnalisations choisies pour chaque ligne (copie figée)
CREATE TABLE order_item_customizations (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_item_id  BIGINT        NOT NULL,
    option_id      BIGINT,
    option_type    VARCHAR(20)   NOT NULL,
    option_code    VARCHAR(50)   NOT NULL,
    label          VARCHAR(100)  NOT NULL,
    extra_price    NUMERIC(10,3) NOT NULL DEFAULT 0,
    CONSTRAINT fk_oic_item FOREIGN KEY (order_item_id) REFERENCES order_items (id) ON DELETE CASCADE,
    CONSTRAINT fk_oic_option FOREIGN KEY (option_id) REFERENCES customization_options (id) ON DELETE SET NULL
);
CREATE INDEX idx_oic_item ON order_item_customizations (order_item_id);

-- ---------------------------------------------------------------------
-- Paiements (acomptes, soldes)
-- ---------------------------------------------------------------------
CREATE TABLE payments (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id         BIGINT        NOT NULL,
    payment_type     VARCHAR(20)   NOT NULL,
    method           VARCHAR(20)   NOT NULL,
    amount           NUMERIC(10,3) NOT NULL,
    status           VARCHAR(20)   NOT NULL DEFAULT 'CONFIRMED',
    transaction_ref  VARCHAR(100),
    paid_at          TIMESTAMP WITH TIME ZONE,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_payments_order FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE CASCADE,
    CONSTRAINT ck_payments_type CHECK (payment_type IN ('DEPOSIT', 'BALANCE', 'FULL')),
    CONSTRAINT ck_payments_method CHECK (method IN ('CASH', 'BANK_TRANSFER', 'D17', 'FLOUCI', 'CARD')),
    CONSTRAINT ck_payments_status CHECK (status IN ('PENDING', 'CONFIRMED', 'REFUNDED')),
    CONSTRAINT ck_payments_amount CHECK (amount > 0)
);
CREATE INDEX idx_payments_order ON payments (order_id);

-- ---------------------------------------------------------------------
-- Livraisons / retraits
-- ---------------------------------------------------------------------
CREATE TABLE deliveries (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id         BIGINT        NOT NULL,
    method           VARCHAR(20)   NOT NULL,
    status           VARCHAR(20)   NOT NULL DEFAULT 'PENDING',
    address_line     VARCHAR(255),
    city             VARCHAR(100),
    governorate      VARCHAR(100),
    postal_code      VARCHAR(10),
    pickup_location  VARCHAR(255),
    fee              NUMERIC(10,3) NOT NULL DEFAULT 0,
    scheduled_date   DATE,
    tracking_number  VARCHAR(100),
    delivered_at     TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uk_deliveries_order UNIQUE (order_id),
    CONSTRAINT fk_deliveries_order FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE CASCADE,
    CONSTRAINT ck_deliveries_method CHECK (method IN ('DELIVERY', 'PICKUP')),
    CONSTRAINT ck_deliveries_status CHECK (status IN ('PENDING', 'SCHEDULED', 'IN_TRANSIT', 'DELIVERED',
                                                      'READY_FOR_PICKUP', 'PICKED_UP', 'FAILED')),
    CONSTRAINT ck_deliveries_address CHECK (method = 'PICKUP' OR (address_line IS NOT NULL AND city IS NOT NULL)),
    CONSTRAINT ck_deliveries_fee CHECK (fee >= 0)
);

-- ---------------------------------------------------------------------
-- Avis clients (achat vérifié + modération)
-- ---------------------------------------------------------------------
CREATE TABLE reviews (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id  BIGINT        NOT NULL,
    user_id     BIGINT        NOT NULL,
    rating      SMALLINT      NOT NULL,
    comment     VARCHAR(1000),
    approved    BOOLEAN       NOT NULL DEFAULT FALSE,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_reviews_product_user UNIQUE (product_id, user_id),
    CONSTRAINT fk_reviews_product FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE CASCADE,
    CONSTRAINT fk_reviews_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT ck_reviews_rating CHECK (rating BETWEEN 1 AND 5)
);
CREATE INDEX idx_reviews_product ON reviews (product_id);
